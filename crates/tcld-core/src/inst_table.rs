const fn legacy_instruction_prefix<const N: usize>(
    lowercase_list_names: bool,
) -> [InstructionDesc; N] {
    let mut table = [TCL_86_INSTRUCTION_TABLE[0]; N];
    let mut index = 0;
    while index < N {
        table[index] = TCL_86_INSTRUCTION_TABLE[index];
        index += 1;
    }
    // Tcl 8.0 through 8.5 called opcode 5 "concat1"; Tcl 8.6 renamed
    // the descriptor to "strcat" without changing its encoding.
    table[5].name = "concat1";
    if lowercase_list_names {
        table[80].name = "listindex";
        table[81].name = "listlength";
    }
    table
}

const fn legacy_opcode_prefix<const N: usize>() -> [Opcode; N] {
    let mut table = [TCL_86_OPCODE_TABLE[0]; N];
    let mut index = 0;
    while index < N {
        table[index] = TCL_86_OPCODE_TABLE[index];
        index += 1;
    }
    table
}

