pub fn instruction_set_for_version(major: i32, minor: i32) -> Option<InstructionSet> {
    match (major, minor) {
        (8, 0..=3) => Some(TCL_80_INSTRUCTION_SET),
        (8, 4) => Some(TCL_84_INSTRUCTION_SET),
        (8, 5) => Some(TCL_85_INSTRUCTION_SET),
        (8, 6) => Some(TCL_86_INSTRUCTION_SET),
        (9, 0) => Some(TCL_9_INSTRUCTION_SET),
        _ => None,
    }
}

