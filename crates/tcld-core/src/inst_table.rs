#[derive(Clone, Copy, Debug)]
pub struct InstructionDesc {
    pub opcode: i32,
    pub argc: i32,
    pub name: &'static str,
    pub byte_count: i32,
    pub stack_effect: i32,
    pub operands: &'static [OpType],
}

impl InstructionDesc {
    pub const fn new(
        opcode: i32,
        argc: i32,
        name: &'static str,
        byte_count: i32,
        stack_effect: i32,
        operands: &'static [OpType],
    ) -> Self {
        Self {
            opcode,
            argc,
            name,
            byte_count,
            stack_effect,
            operands,
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct InstructionSet {
    pub name: &'static str,
    pub instruction_table: &'static [InstructionDesc],
    pub opcode_table: &'static [Opcode],
}

impl InstructionSet {
    pub fn opcode_from_i32(self, value: i32) -> Option<Opcode> {
        if value < 0 {
            return None;
        }
        self.opcode_table.get(value as usize).copied()
    }

    pub fn desc_from_i32(self, value: i32) -> Option<&'static InstructionDesc> {
        if value < 0 {
            return None;
        }
        self.instruction_table.get(value as usize)
    }
}

