#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum OpType {
    None = 0,
    Int1,
    Int4,
    Uint1,
    Uint4,
    Idx4,
    Lvt1,
    Lvt4,
    Aux4,
    Offset1,
    Offset4,
    Lit1,
    Lit4,
    Scls1,
}

impl OpType {
    pub fn mem_size(self) -> i32 {
        match self {
            OpType::Int1
            | OpType::Uint1
            | OpType::Lvt1
            | OpType::Offset1
            | OpType::Lit1
            | OpType::Scls1 => 1,
            OpType::Int4
            | OpType::Uint4
            | OpType::Idx4
            | OpType::Lvt4
            | OpType::Aux4
            | OpType::Offset4
            | OpType::Lit4 => 4,
            OpType::None => 0,
        }
    }
}

