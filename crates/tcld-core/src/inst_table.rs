impl Opcode {
    /// Decode an opcode using the Tcl 8.6 byte assignment.
    ///
    /// Bytecode decoding should normally use
    /// [`InstructionSet::opcode_from_i32`] so the compiled Tcl version selects
    /// the correct byte assignment.
    pub fn from_i32(value: i32) -> Option<Self> {
        if value < 0 {
            return None;
        }
        TCL_86_OPCODE_TABLE.get(value as usize).copied()
    }
}

