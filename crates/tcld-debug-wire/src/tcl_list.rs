//! Tcl-list parser/formatter.
//!
//! The wire format embeds Tcl lists at every level — the frame
//! envelope is a Tcl list, the payload is a Tcl list, individual
//! op/event arguments are Tcl lists. We need a parser that:
//!
//! 1. Round-trips with Tcl's own `list`/`lindex` semantics for the
//!    common cases (whitespace-separated tokens, brace-quoted
//!    elements, backslash-escaped braces inside braces)
//! 2. Never panics on malformed input — every error path returns a
//!    typed `Err`
//! 3. Is the same format-shape both controllers (Rust + Tcl) emit
//!    and consume; V09 in the Tier 4 plan asserts byte-identicality
//!    for shared op sequences
//!
//! Not implemented (and not needed for v2): `\xNN` escapes,
//! double-quoted strings, comment skipping. These are valid Tcl
//! syntax but not generated by our wire emitters.

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TclListError {
    UnterminatedBrace,
    UnexpectedClosingBrace,
}

impl std::fmt::Display for TclListError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnterminatedBrace => write!(f, "unterminated brace in Tcl list"),
            Self::UnexpectedClosingBrace => write!(f, "unexpected `}}` in Tcl list"),
        }
    }
}

impl std::error::Error for TclListError {}

/// Parse a Tcl list into its top-level elements. Brace-quoted
/// elements are unwrapped and their internal `\{` / `\}` / `\\`
/// escapes are decoded. Plain elements are returned as-is.
pub fn tcl_list_parse(s: &str) -> Result<Vec<String>, TclListError> {
    let bytes = s.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        while i < bytes.len() && is_ws(bytes[i]) {
            i += 1;
        }
        if i >= bytes.len() {
            break;
        }
        if bytes[i] == b'}' {
            return Err(TclListError::UnexpectedClosingBrace);
        }
        if bytes[i] == b'{' {
            let (elem, next) = parse_braced(bytes, i)?;
            out.push(elem);
            i = next;
        } else {
            let (elem, next) = parse_plain(bytes, i);
            out.push(elem);
            i = next;
        }
    }
    Ok(out)
}

fn is_ws(b: u8) -> bool {
    matches!(b, b' ' | b'\t' | b'\n' | b'\r')
}

fn parse_plain(bytes: &[u8], start: usize) -> (String, usize) {
    let mut j = start;
    let mut buf = Vec::new();
    while j < bytes.len() && !is_ws(bytes[j]) {
        if bytes[j] == b'\\' && j + 1 < bytes.len() {
            buf.push(bytes[j + 1]);
            j += 2;
            continue;
        }
        buf.push(bytes[j]);
        j += 1;
    }
    (String::from_utf8_lossy(&buf).into_owned(), j)
}

fn parse_braced(bytes: &[u8], start: usize) -> Result<(String, usize), TclListError> {
    debug_assert_eq!(bytes[start], b'{');
    let mut depth: i32 = 1;
    let mut j = start + 1;
    let mut buf = Vec::new();
    while j < bytes.len() {
        let b = bytes[j];
        if b == b'\\' && j + 1 < bytes.len() {
            let next = bytes[j + 1];
            // Inside braces, `\{`, `\}`, and `\\` are decoded; other
            // escapes pass through with the backslash intact (Tcl's
            // behaviour is more nuanced but our emitters only use
            // these three).
            match next {
                b'{' | b'}' | b'\\' => {
                    buf.push(next);
                    j += 2;
                    continue;
                }
                _ => {
                    buf.push(b'\\');
                    buf.push(next);
                    j += 2;
                    continue;
                }
            }
        }
        if b == b'{' {
            depth += 1;
            buf.push(b);
            j += 1;
            continue;
        }
        if b == b'}' {
            depth -= 1;
            if depth == 0 {
                j += 1;
                return Ok((String::from_utf8_lossy(&buf).into_owned(), j));
            }
            buf.push(b);
            j += 1;
            continue;
        }
        buf.push(b);
        j += 1;
    }
    Err(TclListError::UnterminatedBrace)
}

/// Format a list of elements as a Tcl list. Each element is brace-quoted
/// when it contains whitespace, braces, backslashes, or is empty.
pub fn tcl_list_format<I, S>(items: I) -> String
where
    I: IntoIterator<Item = S>,
    S: AsRef<str>,
{
    let parts: Vec<String> = items.into_iter().map(|s| brace_quote(s.as_ref())).collect();
    parts.join(" ")
}

fn brace_quote(s: &str) -> String {
    if s.is_empty() {
        return "{}".to_string();
    }
    let needs_quoting = s.bytes().any(|b| {
        is_ws(b)
            || b == b'{'
            || b == b'}'
            || b == b'\\'
            || b == b'"'
            || b == b'$'
            || b == b'['
            || b == b']'
            || b == b';'
    });
    if !needs_quoting {
        return s.to_string();
    }
    // Tcl's list parser preserves inner content literally between
    // matched braces — nested balanced braces are fine, no escape
    // needed. So we wrap-and-go for balanced input.
    if is_brace_balanced(s) && !contains_unescapable(s) {
        let mut out = String::with_capacity(s.len() + 2);
        out.push('{');
        out.push_str(s);
        out.push('}');
        return out;
    }
    // Fallback: escape inner braces and backslashes via `\<char>`.
    // Used only when the input has unbalanced braces or trailing
    // backslashes that would confuse Tcl's brace counter.
    let mut out = String::with_capacity(s.len() + 2);
    out.push('{');
    for ch in s.chars() {
        match ch {
            '{' => out.push_str("\\{"),
            '}' => out.push_str("\\}"),
            '\\' => out.push_str("\\\\"),
            other => out.push(other),
        }
    }
    out.push('}');
    out
}

fn is_brace_balanced(s: &str) -> bool {
    let mut depth: i32 = 0;
    let mut iter = s.bytes();
    while let Some(b) = iter.next() {
        if b == b'\\' {
            // Skip the next byte if any — it's escaped.
            if iter.next().is_none() {
                return false;
            }
            continue;
        }
        if b == b'{' {
            depth += 1;
        } else if b == b'}' {
            depth -= 1;
            if depth < 0 {
                return false;
            }
        }
    }
    depth == 0
}

/// True if `s` contains characters that would still need escaping
/// even when wrapped in braces — currently only a trailing unescaped
/// backslash, which would consume the closing `}`.
fn contains_unescapable(s: &str) -> bool {
    s.ends_with('\\') && !s.ends_with("\\\\")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_input_yields_empty_list() {
        assert_eq!(tcl_list_parse("").unwrap(), Vec::<String>::new());
    }

    #[test]
    fn whitespace_only_yields_empty_list() {
        assert_eq!(tcl_list_parse("   \t\n  ").unwrap(), Vec::<String>::new());
    }

    #[test]
    fn plain_tokens_split_on_whitespace() {
        assert_eq!(
            tcl_list_parse("a b  c\td").unwrap(),
            vec!["a", "b", "c", "d"]
        );
    }

    #[test]
    fn braced_tokens_preserve_internal_whitespace() {
        assert_eq!(
            tcl_list_parse("{a b} c {d e f}").unwrap(),
            vec!["a b", "c", "d e f"]
        );
    }

    #[test]
    fn nested_braces_are_preserved() {
        assert_eq!(
            tcl_list_parse("{outer {inner}} z").unwrap(),
            vec!["outer {inner}", "z"]
        );
    }

    #[test]
    fn escaped_braces_inside_braces_decode() {
        assert_eq!(tcl_list_parse(r"{a\{b\}c}").unwrap(), vec!["a{b}c"]);
    }

    #[test]
    fn unterminated_brace_returns_error() {
        let err = tcl_list_parse("{open").unwrap_err();
        assert_eq!(err, TclListError::UnterminatedBrace);
    }

    #[test]
    fn unexpected_closing_brace_returns_error() {
        let err = tcl_list_parse("a }").unwrap_err();
        assert_eq!(err, TclListError::UnexpectedClosingBrace);
    }

    #[test]
    fn format_simple_tokens_unquoted() {
        assert_eq!(tcl_list_format(["a", "b", "c"]), "a b c");
    }

    #[test]
    fn format_empty_string_braces() {
        assert_eq!(tcl_list_format(["a", "", "b"]), "a {} b");
    }

    #[test]
    fn format_whitespace_tokens_brace_quoted() {
        assert_eq!(tcl_list_format(["a b", "c"]), "{a b} c");
    }

    #[test]
    fn format_special_chars_brace_quoted() {
        // $, [, ], ", ;, \, {, } — anything Tcl substitutes — gets braces.
        assert_eq!(tcl_list_format(["$x"]), "{$x}");
        assert_eq!(tcl_list_format(["[cmd]"]), "{[cmd]}");
        assert_eq!(tcl_list_format(["a;b"]), "{a;b}");
    }

    #[test]
    fn round_trip_simple() {
        let original = vec!["foo", "bar baz", "qux"];
        let s = tcl_list_format(original.iter().copied());
        let parsed = tcl_list_parse(&s).unwrap();
        assert_eq!(parsed, original);
    }

    #[test]
    fn round_trip_with_braces() {
        let original = vec!["a{b}c", "plain", "two words"];
        let s = tcl_list_format(original.iter().copied());
        let parsed = tcl_list_parse(&s).unwrap();
        assert_eq!(parsed, original);
    }

    #[test]
    fn round_trip_with_dollar_substitution_chars() {
        let original = vec!["expr {$x > 5}", "plain"];
        let s = tcl_list_format(original.iter().copied());
        let parsed = tcl_list_parse(&s).unwrap();
        assert_eq!(parsed, original);
    }
}
